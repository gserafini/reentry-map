/**
 * Parse state-level location searches such as "Washington, USA" or "Texas"
 * into a 2-letter state code. Returns undefined for city/region/location strings.
 */
export function parseStateLocationName(locationName?: string | null): string | undefined {
  if (!locationName) return undefined

  const normalized = locationName.trim().toLowerCase()
  const baseName = normalized.replace(
    /,\s*(usa|us|united states|united states of america)\s*$/i,
    ''
  )

  return US_STATE_NAME_TO_CODE[baseName]
}
